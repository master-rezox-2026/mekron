let currentLang = localStorage.getItem('site_lang') || 'en';

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('site_lang', lang);

    // Update select elements
    if (document.getElementById('lang-select')) document.getElementById('lang-select').value = lang;
    if (document.getElementById('lang-select-mobile')) document.getElementById('lang-select-mobile').value = lang;

    // Apply translations to all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerText = translations[lang][key];
        }
    });

    // Font adjustments for Tamil / Sinhala
    if (lang === 'si') {
        document.body.style.fontFamily = "'Noto Sans Sinhala', 'Poppins', sans-serif";
    } else if (lang === 'ta') {
        document.body.style.fontFamily = "'Noto Sans Tamil', 'Poppins', sans-serif";
    } else {
        document.body.style.fontFamily = "'Poppins', sans-serif";
    }

    // Re-render dynamic services in selected language
    renderDynamicServices();
}

